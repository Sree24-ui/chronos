#!/usr/bin/env python3
"""Generate docs/RESULTS.md from results/*.json. Every number comes from those files; nothing is typed by hand.
   usage: python3 scripts/make_report.py   (run from the project root)"""
import glob, json, math, os, sys
R = 'results'
FILES = [('bench_default.json', 'Default band, policy v2 (the main experiment)'),
         ('bench_wide.json', 'Wide band (4,194,304 ticks), policy v2 (array footprint is large here)'),
         ('bench_policy1.json', 'Default band, policy v1 (density rule; kept as a negative result)'),
         ('bench_heldout.json', 'HELD-OUT: `market_like` workload (written after the thresholds were frozen), default band'),
         ('bench_heldout_wide.json', 'HELD-OUT: `market_like`, wide band'),
         ('bench_newseed.json', 'HELD-OUT: the original six workloads on a fresh seed (thresholds frozen)'),
         ('lobster.json', 'Recorded LOBSTER-format market data replay')]
NAMES = {'std': 'STL baseline', 'tree': 'tree', 'array': 'array', 'adaptive': 'adaptive'}
def load(f):
    p = os.path.join(R, f)
    return json.load(open(p)) if os.path.exists(p) else None
def us(n): return f'{n/1000:.2f} µs' if n >= 1000 else f'{n:.0f} ns'
out = ['# Benchmark results', '',
       '*Generated by `scripts/make_report.py` from `results/*.json`. Do not edit by hand; re-run the benchmarks and regenerate.*', '',
       'All figures are **simulated in-process replay on one thread** of synthetic commands (not exchange throughput). '
       'Throughput is the median over trials of an untimed pass; latencies come from a separate per-command-timed pass, so they include two clock reads '
       '(`clockReadNs` below) and are quantized to the clock tick (about 42 ns on Apple silicon). Heap is live malloc bytes after the run minus before. '
       '"consistent" means every strategy produced the identical trade stream (hash) and final active-order count.', '']
for f, title in FILES:
    d = load(f)
    if not d: continue
    c, e, rs = d['config'], d['env'], d['results']
    out += [f'## {title}', '', f"`{f}` · n={c['n']:,} · seed {c['seed']} · {c['trials']} trials (+{c['warmup']} warm-up) · band {c['band'][1]-c['band'][0]:,} ticks · policy v{c.get('policy','?')} · "
            f"{e['os']} {e['arch']} · {e['compiler'].split(' (')[0]} · clock read ≈ {e['clockReadNs']} ns", '',
            '| workload | strategy | Mops/s (median) | trial range | avg | p50 | p99 | p99.9 | max | heap MB | allocs | switches | consistent |', '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|:-:|']
    for r in rs:
        t = r['trialOps']; l = r['lat']
        out.append(f"| {r['workload']} | {NAMES[r['strategy']]} | {r['opsPerSec']/1e6:.2f} | {min(t)/1e6:.2f}–{max(t)/1e6:.2f} | {us(l['avg'])} | {us(l['p50'])} | {us(l['p99'])} | {us(l['p999'])} | {us(l['max'])} | {r['heapMB']:.1f} | {r['allocs']:,} | {r['migrations']} | {'yes' if r['consistent'] else '**NO**'} |")
    by = {(r['workload'], r['strategy']): r for r in rs}
    ws = list(dict.fromkeys(r['workload'] for r in rs))
    if all((w, s) in by for w in ws for s in ('tree', 'array', 'adaptive')):
        out += ['', '**Ratios (from the table above):**', '', '| workload | adaptive ÷ array (Mops/s) | adaptive ÷ tree (Mops/s) | array ÷ tree (Mops/s) | adaptive ÷ array (heap) | adaptive ÷ tree (heap) | fastest fixed |', '|---|---:|---:|---:|---:|---:|---|']
        for w in ws:
            a, t, ad = by[(w, 'array')], by[(w, 'tree')], by[(w, 'adaptive')]
            fastest = 'array' if a['opsPerSec'] >= t['opsPerSec'] else 'tree'
            out.append(f"| {w} | {ad['opsPerSec']/a['opsPerSec']:.2f}× | {ad['opsPerSec']/t['opsPerSec']:.2f}× | {a['opsPerSec']/t['opsPerSec']:.2f}× | {ad['heapMB']/a['heapMB']:.2f}× | {ad['heapMB']/t['heapMB']:.2f}× | {fastest} |")
        # honest overlap check: do adaptive and array trial ranges overlap?
        ov = [w for w in ws if max(by[(w,'adaptive')]['trialOps']) >= min(by[(w,'array')]['trialOps']) and min(by[(w,'adaptive')]['trialOps']) <= max(by[(w,'array')]['trialOps'])]
        out += ['', f"Workloads where adaptive's and array's per-trial throughput ranges overlap (difference not distinguishable from run-to-run noise): {', '.join(ov) if ov else 'none'}."]
    bad = [f"{r['workload']}/{r['strategy']}" for r in rs if not r['consistent']]
    out += ['', 'Consistency check: ' + ('**FAILED for ' + ', '.join(bad) + '**' if bad else 'all strategies agree on every workload.'), '']
ms = sorted(glob.glob(os.path.join(R, 'machines', '*.json')))
if ms:
    out += ['## Other machines (same benchmark, default band, run by teammates)', '',
            'Geometric mean over all workloads in each file. A claim that holds on every machine is stronger than one measured on a single laptop.', '',
            '| file | OS / arch | compiler | n | array ÷ STL | tree ÷ STL | adaptive ÷ array | adaptive heap ÷ array |', '|---|---|---|---:|---:|---:|---:|---:|']
    def gm(v): return math.exp(sum(math.log(x) for x in v) / len(v)) if v else float('nan')
    for f in ms:
        d = json.load(open(f)); by = {(r['workload'], r['strategy']): r for r in d['results']}; ws = list(dict.fromkeys(r['workload'] for r in d['results']))
        def ratio(a, b, key): return gm([by[(w, a)][key] / by[(w, b)][key] for w in ws if (w, a) in by and (w, b) in by and by[(w, b)][key] > 0])
        e = d['env']
        out.append(f"| {os.path.basename(f)} | {e['os']} {e['arch']} | {e['compiler'].split(' (')[0]} | {d['config']['n']:,} | {ratio('array','std','opsPerSec'):.2f}× | {ratio('tree','std','opsPerSec'):.2f}× | {ratio('adaptive','array','opsPerSec'):.2f}× | {ratio('adaptive','array','heapMB'):.2f}× |")
    out.append('')
open('docs/RESULTS.md', 'w').write('\n'.join(out) + '\n')
print('wrote docs/RESULTS.md', len(out), 'lines')
